-- SAVED ROUTES

create table public.saved_routes (
    id uuid
        primary key
        default gen_random_uuid(),

    user_id uuid
        not null
        references auth.users(id)
        on delete cascade,

    route_name varchar(150)
        not null,

    origin_place_id varchar(255),

    origin_name varchar(255)
        not null,

    origin_location extensions.geography(Point, 4326)
        not null,

    destination_place_id varchar(255),

    destination_name varchar(255)
        not null,

    destination_location extensions.geography(Point, 4326)
        not null,

    route_preference varchar(30)
        not null
        default 'fastest',

    created_at timestamptz
        not null
        default now(),

    updated_at timestamptz
        not null
        default now(),

    last_used_at timestamptz,

    constraint saved_routes_name_check
        check (
            char_length(trim(route_name)) >= 1
        ),

    constraint saved_routes_preference_check
        check (
            route_preference in (
                'shortest_distance',
                'cheapest',
                'least_walking',
                'least_time'
            )
        )
);

create index saved_routes_user_created_idx
on public.saved_routes (
    user_id,
    created_at desc
);

create index saved_routes_origin_location_gix
on public.saved_routes
using gist (origin_location);

create index saved_routes_destination_location_gix
on public.saved_routes
using gist (destination_location);

-- FARE CHANGE REQUESTS

create table public.fare_change_requests (
    id uuid
        primary key
        default gen_random_uuid(),

    submitted_by uuid
        not null
        references auth.users(id)
        on delete cascade,

    operator_name varchar(200)
        not null,

    transport_mode varchar(50)
        not null,

    transport_line varchar(200),

    old_fare numeric(10, 2),

    proposed_fare numeric(10, 2)
        not null,

    effective_date date,

    description text,

    source_url text,

    evidence_storage_path text,

    status varchar(30)
        not null
        default 'pending',

    reviewed_by uuid
        references auth.users(id)
        on delete set null,

    reviewed_at timestamptz,

    review_note text,

    created_at timestamptz
        not null
        default now(),

    updated_at timestamptz
        not null
        default now(),

    constraint fare_requests_transport_mode_check
        check (
            transport_mode in (
                'bus',
                'bts',
                'mrt',
                'arl',
                'train',
                'boat',
                'other'
            )
        ),

    constraint fare_requests_old_fare_check
        check (
            old_fare is null
            or old_fare >= 0
        ),

    constraint fare_requests_proposed_fare_check
        check (
            proposed_fare >= 0
        ),

    constraint fare_requests_status_check
        check (
            status in (
                'pending',
                'approved',
                'rejected',
                'needs_more_information'
            )
        )
);

create index fare_requests_submitted_by_idx
on public.fare_change_requests (submitted_by);

create index fare_requests_status_created_idx
on public.fare_change_requests (
    status,
    created_at desc
);

