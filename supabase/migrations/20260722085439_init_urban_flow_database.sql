-- USER PROFILES

create table public.profiles (
    id uuid primary key
        references auth.users(id)
        on delete cascade,

    display_name varchar(100) not null,

    avatar_url text,

    preferred_language varchar(5)
        not null
        default 'th',

    account_status varchar(20)
        not null
        default 'active',

    reputation_score integer
        not null
        default 0,

    created_at timestamptz
        not null
        default now(),

    updated_at timestamptz
        not null
        default now(),

    constraint profiles_language_check
        check (
            preferred_language in ('th', 'en')
        ),

    constraint profiles_account_status_check
        check (
            account_status in (
                'active',
                'suspended',
                'deleted'
            )
        ),

    constraint profiles_reputation_check
        check (reputation_score >= 0)
);

-- REPORT CATEGORIES

create table public.report_categories (
    id smallint
        generated by default as identity
        primary key,

    code varchar(50)
        not null
        unique,

    name_th varchar(100)
        not null,

    name_en varchar(100)
        not null,

    default_expiry_minutes integer,

    is_active boolean
        not null
        default true,

    created_at timestamptz
        not null
        default now(),

    constraint report_categories_expiry_check
        check (
            default_expiry_minutes is null
            or default_expiry_minutes > 0
        )
);

-- INCIDENT REPORTS

create table public.incident_reports (
    id uuid
        primary key
        default gen_random_uuid(),

    category_id smallint
        not null
        references public.report_categories(id),

    reported_by uuid
        not null
        references auth.users(id)
        on delete cascade,

    title varchar(200)
        not null,

    description text,

    -- พิกัด WGS84 ร่วมกับ Google Maps
    location extensions.geography(Point, 4326)
        not null,

    place_name varchar(255),

    severity varchar(20)
        not null
        default 'medium',

    status varchar(20)
        not null
        default 'pending',

    occurred_at timestamptz
        not null
        default now(),

    expires_at timestamptz,

    confidence_score numeric(6, 2)
        not null
        default 0,

    duplicate_of_report_id uuid
        references public.incident_reports(id)
        on delete set null,

    created_at timestamptz
        not null
        default now(),

    updated_at timestamptz
        not null
        default now(),

    constraint incident_reports_title_check
        check (
            char_length(trim(title)) >= 3
        ),

    constraint incident_reports_severity_check
        check (
            severity in (
                'low',
                'medium',
                'high',
                'critical'
            )
        ),

    constraint incident_reports_status_check
        check (
            status in (
                'pending',
                'verified',
                'rejected',
                'resolved',
                'expired'
            )
        ),

    constraint incident_reports_confidence_check
        check (
            confidence_score >= 0
            and confidence_score <= 100
        ),

    constraint incident_reports_expiry_check
        check (
            expires_at is null
            or expires_at > created_at
        )
);

-- Index สำหรับค้นหาเหตุการณ์ใกล้ตำแหน่ง 

