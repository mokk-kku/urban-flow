-- CREATE INCIDENT FUNCTION

create or replace function public.create_incident_report(
    p_category_code text,
    p_title text,
    p_description text,
    p_place_name text,
    p_latitude double precision,
    p_longitude double precision,
    p_severity text default 'medium'
)
returns uuid
language plpgsql
security invoker
set search_path = public, extensions
as $$
declare
    v_category_id smallint;
    v_report_id uuid;
    v_expiry_minutes integer;
begin
    if auth.uid() is null then
        raise exception 'Authentication required';
    end if;

    if p_latitude < -90 or p_latitude > 90 then
        raise exception 'Invalid latitude';
    end if;

    if p_longitude < -180 or p_longitude > 180 then
        raise exception 'Invalid longitude';
    end if;

    if p_severity not in (
        'low',
        'medium',
        'high',
        'critical'
    ) then
        raise exception 'Invalid severity';
    end if;

    select
        id,
        default_expiry_minutes
    into
        v_category_id,
        v_expiry_minutes
    from public.report_categories
    where code = p_category_code
      and is_active = true;

    if v_category_id is null then
        raise exception 'Invalid report category';
    end if;

    insert into public.incident_reports (
        category_id,
        reported_by,
        title,
        description,
        place_name,
        location,
        severity,
        expires_at
    )
    values (
        v_category_id,
        auth.uid(),
        trim(p_title),
        nullif(trim(p_description), ''),
        nullif(trim(p_place_name), ''),
        extensions.st_setsrid(
            extensions.st_makepoint(
                p_longitude,
                p_latitude
            ),
            4326
        )::extensions.geography,
        p_severity,
        case
            when v_expiry_minutes is null
                then null
            else
                now()
                + make_interval(
                    mins => v_expiry_minutes
                )
        end
    )
    returning id into v_report_id;

    return v_report_id;
end;
$$;